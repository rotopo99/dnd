function weaponFrom(id, adj) {
  const it = WEAPONS[id];
  if (!it) throw new Error(`enemies-v3: unknown weapon "${id}"`);
  return {
    name: it.name, dice: it.dice, dmgType: it.dmgType, stat: it.stat, range: it.range, hit: (it.hit || 0) + adj,
    rof: it.rof, recoil: it.recoil, ap: it.ap || 0, onHit: it.onHit || [], type: it.type, twoHanded: it.twoHanded, noise: it.noise, item: it.id,
  };
}

function foe(o) {
  const prof = o.level >= 5 ? 3 : 2;
  const gear = o.gear || {};
  let weapon = null;
  if (o.weapon !== undefined) weapon = o.weapon && { hit: -1, ...o.weapon };
  else if (gear.weapon) weapon = weaponFrom(gear.weapon, o.hitAdj ?? -1);
  if (weapon && weapon.attack == null) weapon.attack = mod(o.stats[weapon.stat]) + prof + 1 + (weapon.hit || 0);
  let kb = o.kb;
  if (kb == null) {
    const ar = gear.armor ? ARMOR[gear.armor] : null;
    if (gear.armor && !ar) throw new Error(`enemies-v3: unknown armor "${gear.armor}"`);
    const cap = ar && ar.dexCap != null ? ar.dexCap : 99;
    kb = 10 + (ar ? ar.kb : 0) + Math.min(mod(o.stats.dex), cap) + (o.kbAdj || 0);
  }
  const items = gear.items || [];
  const inventory = {};
  for (const id of items) inventory[id] = (inventory[id] || 0) + 1;
  const { hitAdj, kbAdj, ...rest } = o;
  return {
    tags: ['organic'], enr: 0, speed: 6, castStat: null, abilities: [], resist: {}, immuneStatus: [], ai: 'melee', xp: 0,
    faction: null, rank: 'grunt', places: [], canon: [],
    ...rest, kb, weapon, gear: { weapon: gear.weapon || null, armor: gear.armor || null, items }, inventory, loot: o.loot || null,
  };
}

