// Эпилог: ключ исхода = 'together' | 'parted' | 'tragedy'. Определяется по финальному состоянию:
//   tragedy — партнёр погиб (romance-lost);  together — bond ≥ 70 к финалу и нет разрыва;  parted — иначе (разрыв / bond < 70).
export function romanceEpilogueKey(state) {
  if (state?.lost) return 'tragedy';
  if (state?.broken) return 'parted';
  return (state?.bond ?? 0) >= 70 ? 'together' : 'parted';
}

export function romanceStage(bond) {
  let out = ROMANCE_RULES.stages[0];
  for (const s of ROMANCE_RULES.stages) if (bond >= s.min) out = s;
  return out;
}
