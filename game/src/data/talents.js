export const jobsOf = (clsId) => Object.keys(JOB_GROUPS).filter((g) => JOB_GROUPS[g].classes.includes(clsId));

/**
 * Можно ли взять талант. ctx: { race, cls, origin, alignment, stats, level, weaponRange, tags }.
 * race/cls/origin — id; stats — итоговые значения; weaponRange — дальность оружия класса/пути.
 */
export function talentAllowed(t, ctx) {
  if (!t || t.todo) return false;
  const r = t.req || {};
  if (r.races && !r.races.includes(ctx.race)) return false;
  if (r.jobs && !r.jobs.some((g) => JOB_GROUPS[g]?.classes.includes(ctx.cls))) return false;
  if (r.origins && !r.origins.includes(ctx.origin)) return false;
  if (r.alignment && r.alignment !== ctx.alignment) return false;
  if (r.level && (ctx.level || 1) < r.level) return false;
  if (r.tags && !r.tags.some((x) => (ctx.tags || []).includes(x))) return false;
  if (r.weapon === 'melee' && (ctx.weaponRange ?? 1) > 1) return false;
  if (r.weapon === 'ranged' && (ctx.weaponRange ?? 1) <= 1) return false;
  if (r.stats) for (const k in r.stats) if ((ctx.stats?.[k] ?? 0) < r.stats[k]) return false;
  return true;
}

/** Таланты для слота создания ('race' | 'job' | 'faction' | 'alignment'). */
export const talentsForSlot = (slot, ctx) => LIST.filter((t) => t.slot === slot && talentAllowed(t, ctx));
