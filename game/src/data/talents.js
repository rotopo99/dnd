//
// Поля таланта:
//   id, name, slot      — 'race' | 'job' | 'faction' | 'alignment' (слоты создания)
//                         | 'learned' | 'mutation' | 'implant' | 'mystic' | 'unique' | 'stat' (получаются в мире)
//   kind                — 'combat' | 'world' | 'both'; всё, кроме 'world', считается боевым (лимит COMBAT_TALENT_LIMIT)
//   req                 — { races?, jobs?, origins?, alignment?, stats?, weapon?: 'melee'|'ranged', tags?, level? }
//   source              — { kind: 'creation'|'level'|'trainer'|'quest'|'rep'|'implant'|'mutation'|'cyberspace',
//                           trainer?: id фракции/NPC-роли, cost?: креды, rep?: порог, item? }
//   passives            — пассивки по схеме core-rules (`op`); id/name/desc подставляются из таланта
//   abilities           — способности по схеме core-rules (id с префиксом 'talent-')
//   world               — эффекты вне боя: { check, bonus } | { check, adv: true } | { worldFlag, value? } (см. WORLD_FLAGS)
//   todo                — нужна доработка движка/мира; такой талант НЕ предлагается игроку
//   canon               — источник или 'вне канона: причина'
//
// Сила: боевой талант ≈ +3–5 п.п. к вкладу героя в бой партии. Большинство — «раз за бой».
// Классы и враги этим файлом не меняются.

