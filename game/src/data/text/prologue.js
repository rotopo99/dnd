  PROLOGUE[`${key}@${race}`] ?? PROLOGUE[`${key}@${String(race).split('-')[0]}`] ?? PROLOGUE[key];

// Speaker display name for a `who` id.
export const speaker = (who) => PROLOGUE[`who.${who}`] ?? who;
