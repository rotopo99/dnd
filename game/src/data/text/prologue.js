// Race-aware lookup: exact race variant → '@mutant' for mutant-beast/mutant-plant → base key.
export const line = (key, race) =>
  PROLOGUE[`${key}@${race}`] ??
  (race && race.startsWith('mutant-') ? PROLOGUE[`${key}@mutant`] : undefined) ??
  PROLOGUE[key];

