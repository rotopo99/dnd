// Сцены проверок контент-волны 1 (формат — world/check-scenes.js; ключи — `${quest}/${stage}#путь`).
// Номера подцелей `s<N>` — с 1 (как в quests.js). Флаги успеха (`w1-*`) ставит fx.flags: это «доказательства» и «спасённые» объекты.
// Подходы: skills ⊆ goal.skills, item/companion — необязательные усилители. Данные чистые (без импортов).

const A = (id, label, skills, extra = {}) => ({ id, label, skills, ...extra });
const O = (text, fx) => ({ text: Array.isArray(text) ? text : [text], ...(fx ? { fx } : {}) });
// S: сцена; крит-исходы по умолчанию = успех/провал + небольшой бонус/штраф
const S = (prolog, approaches, ok, bad, okFx, badFx, crit = {}) => ({
  prolog,
  approaches,
  outcomes: {
    success: O(ok, okFx),
    fail: O(bad, badFx),
    critSuccess: O(crit.ok || [...ok, 'И сделано так чисто, что хочется поклониться самому себе.'], { ...(okFx || {}), xpPct: 25 }),
    critFail: O(crit.bad || [...bad, 'Хуже того: это видели все, кому это видеть не стоило.'], { ...(badFx || {}), mrl: -2 }),
  },
});

