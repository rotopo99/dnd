//
// Ключ сцены: `${questId}/${stageId}` + (`#${путь}` если проверка вложена): путь — как в слотах quests.js:
//   `o:<optionId>` (проверка внутри опции choice), `s<N>` (N-я подцель `all`), `s<N>o:<optionId>` (опция в подцели).
// Сцена: {
//   at?: [ключи]            — сцена обслуживает ещё и эти ключи (одинаковые проверки: маяки, закладки);
//   prolog: [1–3 строки],
//   approaches: [2–4 × { id, label, skills: [навык ⊆ goal.skills], dcMod?, adv?, bonus?,
//                        item?: id (нужен в рюкзаке), consume?: true, companion?: npc id (нужен активным в партии),
//                        hint? }],     — dcMod: −/+ к СЛ; bonus: плоский бонус к броску; adv: преимущество
//   outcomes: { success, fail, critSuccess, critFail } — каждый { text: [строки], fx?: Fx }
// }
// Fx (последствия сверх quests.js; fail/критпровал по-прежнему запускают onFail стадии):
//   hp, mrl — Δ герою (отрицательное = урон), party: true — всем активным; days — дни игрового времени (passDays);
//   rep { faction: Δ }, credits, items [{ item, n }], removeItems, flags [..], xpPct — доп. опыт в % от награды стадии.
// critSuccess = натуральная 20 (заменяет success, обязателен успех). critFail = натуральная 1 (заменяет fail, обязателен провал).
// Если у выбранного подхода нет своего исхода, берётся общий. Подход-компаньон: перед броском реплика (`say`) — опц.

