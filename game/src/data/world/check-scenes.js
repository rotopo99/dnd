/**
 * Авто-обёртка: сцена для любой проверки без своей записи в CHECK_SCENES.
 * goal — цель {skills, dc, ...}; stageText — текст стадии; возвращает сцену того же формата.
 * Подходы: до 4 навыков цели (порядок как в goal.skills), outcomes — по первому навыку (общий текст).
 */
export function autoScene(goal, stageText = '') {
  const skills = (goal.skills || []).filter((s) => SKILL_TEMPLATES[s]).slice(0, 4);
  const main = SKILL_TEMPLATES[skills[0]] || SKILL_TEMPLATES.perception;
  const subst = (s) => s;
  const mk = (txt, fx) => ({ text: [subst(txt)], ...(fx && Object.keys(fx).length ? { fx } : {}) });
  return {
    auto: true,
    prolog: [stageText, main.prolog].filter(Boolean).slice(0, 3),
    approaches: skills.map((s) => ({ id: s, label: SKILL_TEMPLATES[s].label, skills: [s] })),
    outcomes: {
      success: mk(main.success), fail: mk(main.fail, main.fx.fail),
      critSuccess: mk(main.critSuccess, { xpPct: 15 }), critFail: mk(main.critFail, main.fx.critFail),
    },
  };
}

/** Ключ слота проверки: `${qid}/${stageId}` + (`#${path}`). */
export const checkKey = (qid, stageId, path = '') => `${qid}/${stageId}${path ? `#${path}` : ''}`;

/** Сцена по ключу (с учётом `at`) или авто-обёртка. */
export function sceneFor(key, goal, stageText) {
  const hit = CHECK_SCENES[key] || Object.values(CHECK_SCENES).find((s) => s.at?.includes(key));
  return hit || autoScene(goal, stageText);
}
